-- Grant schema-level permissions
GRANT ALL ON SCHEMA public TO mars_agent;
GRANT CREATE ON SCHEMA public TO mars_agent;

-- Grant permissions on future tables and sequences created in public schema
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO mars_agent;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO mars_agent;

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

CREATE TABLE agents (
       agent_name TEXT,
       agent_uuid UUID,
       hostname TEXT,
       port_number INTEGER,
       live_flag BOOLEAN,
       information JSONB);
       -- agentuuid and liveflag are not keep compatibility with SQLite and Postgres
       -- agents kept on an orchestration agent instance value: self.agents :={uuid: {agent}, ...}

CREATE TABLE message_log (
       message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
       from_agent TEXT,
       from_agent_uuid UUID,
       to_agent TEXT,
       to_agent_uuid UUID,
       message JSONB);
       -- fromagentuuid and toagentuuid are not keep compatibility with SQLite and Postgres
